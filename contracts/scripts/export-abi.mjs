// Writes the WildsentiaChallenges ABI for the server from Foundry's build output.
//   node contracts/scripts/export-abi.mjs           write packages/server/src/challenges/challengesAbi.ts
//   node contracts/scripts/export-abi.mjs --check   fail if that file is missing or out of date
// Run `forge build` (or `forge test`) in contracts/ first.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const contracts = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const artifact = resolve(contracts, 'out/WildsentiaChallenges.sol/WildsentiaChallenges.json');
const target = resolve(contracts, '../packages/server/src/challenges/challengesAbi.ts');

if (!existsSync(artifact)) {
  console.error('No build output: run `forge build` in contracts/ first.');
  process.exit(1);
}
const { abi } = JSON.parse(readFileSync(artifact, 'utf8'));
const source = '// Generated by contracts/scripts/export-abi.mjs from contracts/src/WildsentiaChallenges.sol.\n'
  + '// Do not edit; rebuild the contract and run the script again.\n'
  + `export const challengesAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== source) {
    console.error('packages/server/src/challenges/challengesAbi.ts is out of date: run node contracts/scripts/export-abi.mjs');
    process.exit(1);
  }
  console.log('Challenges ABI is up to date.');
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, source);
  console.log(`Wrote ${target}`);
}
