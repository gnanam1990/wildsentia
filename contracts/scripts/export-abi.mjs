// Writes the contracts' ABIs for the server from Foundry's build output.
//   node contracts/scripts/export-abi.mjs           write packages/server/src/challenges/*Abi.ts
//   node contracts/scripts/export-abi.mjs --check   fail if any of them is missing or out of date
// Run `forge build` (or `forge test`) in contracts/ first.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const contracts = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EXPORTS = [
  { contract: 'WildsentiaChallenges', name: 'challengesAbi', file: 'challengesAbi.ts' },
  { contract: 'WildsentiaAttempts', name: 'attemptsAbi', file: 'attemptsAbi.ts' },
  { contract: 'WildsentiaBounties', name: 'bountiesAbi', file: 'bountiesAbi.ts' },
];

let stale = false;
for (const { contract, name, file } of EXPORTS) {
  const artifact = resolve(contracts, `out/${contract}.sol/${contract}.json`);
  const target = resolve(contracts, `../packages/server/src/challenges/${file}`);
  if (!existsSync(artifact)) {
    console.error('No build output: run `forge build` in contracts/ first.');
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(artifact, 'utf8'));
  const source = `// Generated by contracts/scripts/export-abi.mjs from contracts/src/${contract}.sol.\n`
    + '// Do not edit; rebuild the contract and run the script again.\n'
    + `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== source) { console.error(`packages/server/src/challenges/${file} is out of date: run node contracts/scripts/export-abi.mjs`); stale = true; }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, source);
    console.log(`Wrote ${target}`);
  }
}
if (stale) process.exit(1);
if (process.argv.includes('--check')) console.log('Contract ABIs are up to date.');
